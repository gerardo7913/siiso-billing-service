-- Legacy tables the rates use, real structure (SHOW CREATE TABLE; empresa reduced to its columns here).
CREATE TABLE `empresa` (
  `CDGEMPRESA` varchar(5) NOT NULL,
  `NBREMPRESA` varchar(100) DEFAULT NULL,
  `DEPENDENCIA_EMPRESA` varchar(5) DEFAULT NULL,
  PRIMARY KEY (`CDGEMPRESA`)
) ENGINE=MyISAM DEFAULT CHARSET=latin1;

CREATE TABLE `tarifa` (
  `CDGEXAMEN` varchar(7) NOT NULL,
  `CDGEMPRESA` varchar(5) NOT NULL,
  `TIPOTARIFA` char(1) NOT NULL DEFAULT '',
  `VALORTARIFA` float(12,2) DEFAULT NULL,
  `NIVELCOMPLEJIDAD` char(1) DEFAULT NULL,
  `UVR` varchar(10) NOT NULL DEFAULT '0',
  `HABI` char(1) DEFAULT '1',
  PRIMARY KEY (`CDGEXAMEN`,`CDGEMPRESA`,`TIPOTARIFA`) USING BTREE,
  KEY `TARIFA` (`CDGEXAMEN`,`CDGEMPRESA`)
) ENGINE=MyISAM DEFAULT CHARSET=latin1;

CREATE TABLE `descuento` (
  `CODNIVEL` char(2) NOT NULL DEFAULT '',
  `CDGEMPRESA` varchar(5) NOT NULL,
  `CUOTA_MODERADA` float DEFAULT NULL,
  `CUOTA_COPAGO` float DEFAULT NULL,
  PRIMARY KEY (`CODNIVEL`,`CDGEMPRESA`)
) ENGINE=MyISAM DEFAULT CHARSET=latin1;
